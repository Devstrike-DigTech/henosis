package com.devstrike.henosis.core.init

import com.devstrike.henosis.core.api.ApiClass
import com.devstrike.henosis.core.api.ApiClassKind
import com.devstrike.henosis.core.api.ApiModel
import com.devstrike.henosis.core.inspect.InspectedMember
import com.devstrike.henosis.core.inspect.Inspector
import com.devstrike.henosis.core.types.KotlinTypes
import com.devstrike.henosis.core.types.SupportLevel

/**
 * Writes the starter `henosis.yaml` for `heno init`: a complete, loadable config with every
 * bindable class listed as a commented-out facade, so the user only uncomments what they want.
 */
object StarterConfig {
    /**
     * @param aarPath the value to write under `source.aar`, as the user should see it.
     * @param name the base name; see [deriveName].
     */
    fun render(
        model: ApiModel,
        aarPath: String,
        name: String,
        henosisVersion: String,
    ): String {
        val report = Inspector.inspect(model).classes.associateBy { it.name }
        val facades = model.classes.filter { it.kind == ApiClassKind.CLASS && it.typeParameters.isEmpty() }
        val types = model.classes.filter { it.kind == ApiClassKind.DATA_CLASS || it.kind == ApiClassKind.ENUM_CLASS }
        return buildString {
            appendLine("# Generated by Henosis $henosisVersion as a starting point; edit freely.")
            appendLine("# Uncomment the classes and members you want to expose. Signatures come from the SDK,")
            appendLine("# so only names are listed here. Overloads are selected as name(Type, Type).")
            appendLine("# Reference: docs/config.md")
            appendLine()
            appendLine("name: $name")
            appendLine("version: 0.1.0")
            appendLine("source:")
            appendLine("  aar: ${yamlString(aarPath)}")
            appendLine("facades:")
            if (facades.isEmpty()) appendLine("  # (no plain public classes with a usable constructor were found)")
            facades.forEach { cls -> appendFacade(cls, report.getValue(cls.name).functions, report.getValue(cls.name).properties) }
            appendLine("types:")
            appendLine("  # Data classes and enums used by the facades are included automatically; list extras here.")
            appendLine("  include: []")
            types.forEach { appendLine("  #   - ${it.name}") }
            appendLine("targets:")
            appendLine("  flutter:")
            appendLine("    package: $name")
            appendLine("    org: com.example")
            appendLine("  react_native:")
            appendLine("    package: ${yamlString(name.replace('_', '-'))}")
            appendLine("    module: ${pascalCase(name)}")
        }
    }

    private fun StringBuilder.appendFacade(
        cls: ApiClass,
        functions: List<InspectedMember>,
        properties: List<InspectedMember>,
    ) {
        val hasContext = cls.constructors.any { c -> c.parameters.size == 1 && c.parameters[0].type.name == KotlinTypes.ANDROID_CONTEXT }
        val hasNoArg = cls.constructors.any { it.parameters.isEmpty() }
        appendLine("  # - class: ${cls.name}")
        when {
            hasContext -> appendLine("  #   constructor: context")
            hasNoArg -> appendLine("  #   constructor: none")
            else -> appendLine("  #   constructor: none   # unsupported: no public no-argument or Context constructor")
        }
        val overloaded =
            cls.functions
                .groupingBy { it.name }
                .eachCount()
                .filterValues { it > 1 }
                .keys
        val events =
            cls.properties.filter { it.type.name == KotlinTypes.FLOW } +
                cls.functions.filter { it.parameters.isEmpty() && it.returnType.name == KotlinTypes.FLOW }
        val eventNames =
            events
                .map {
                    if (it is com.devstrike.henosis.core.api.ApiProperty) {
                        it.name
                    } else {
                        (it as com.devstrike.henosis.core.api.ApiFunction)
                            .name
                    }
                }.toSet()
        val methods = cls.functions.filter { it.name !in eventNames }
        if (methods.isNotEmpty()) {
            appendLine("  #   methods:")
            methods.forEach { fn ->
                val selector =
                    if (fn.name in
                        overloaded
                    ) {
                        "${fn.name}(${fn.parameters.joinToString(", ") { it.type.render() }})"
                    } else {
                        fn.name
                    }
                val status =
                    functions.firstOrNull {
                        it.signature.contains(" ${fn.name}(") &&
                            it.signature.contains(fn.parameters.joinToString(", ") { "${it.name}: ${it.type.render()}" })
                    }
                appendLine("  #     - $selector${annotation(status)}")
            }
        }
        if (eventNames.isNotEmpty()) {
            appendLine("  #   events:")
            eventNames.sorted().forEach { name ->
                val status = properties.firstOrNull { it.name == name } ?: functions.firstOrNull { it.name == name }
                appendLine("  #     - $name${annotation(status)}")
            }
        }
    }

    private fun annotation(member: InspectedMember?): String =
        when (member?.status) {
            SupportLevel.UNSUPPORTED -> "   # unsupported: ${member.findings.first { it.level == SupportLevel.UNSUPPORTED }.message}"
            SupportLevel.WARN -> "   # warn: ${member.findings.first().message}"
            else -> ""
        }

    private fun yamlString(value: String): String =
        if (Regex("[A-Za-z0-9_./-]+").matches(value) &&
            !value.startsWith("-")
        ) {
            value
        } else {
            "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
        }

    private fun pascalCase(name: String): String =
        name
            .split('_')
            .filter {
                it.isNotEmpty()
            }.joinToString("") { part -> part.replaceFirstChar { it.uppercase() } }

    /**
     * Derives a base name from an archive file name: `sample-sdk-release.aar` becomes `sample_sdk`.
     * Build-variant suffixes are dropped and anything that is not a letter or digit becomes `_`.
     */
    fun deriveName(fileName: String): String {
        var base = fileName.substringBeforeLast('.').lowercase()
        base =
            base
                .removeSuffix("-release")
                .removeSuffix("-debug")
                .removeSuffix("_release")
                .removeSuffix("_debug")
        base = base.replace(Regex("[^a-z0-9]+"), "_").trim('_')
        if (base.isEmpty() || !base[0].isLetter()) base = "sdk_$base".trim('_')
        return base
    }
}
