package com.devstrike.henosis.core.codegen

import java.nio.file.Files
import java.nio.file.Path

/**
 * One generated text file, with a path relative to the package root (always `/`-separated).
 * [executable] marks scripts such as `gradlew` that must carry the execute bit.
 */
data class GeneratedFile(
    val path: String,
    val content: String,
    val executable: Boolean = false,
)

/** A binary file generated from embedded bytes (for example the Gradle wrapper jar). Not part of golden snapshots. */
data class BinaryFile(
    val path: String,
    val bytes: ByteArray,
) {
    override fun equals(other: Any?): Boolean = other is BinaryFile && other.path == path && other.bytes.contentEquals(bytes)

    override fun hashCode(): Int = path.hashCode()
}

/** A binary that must be copied verbatim into the package (the SDK's `.aar`). */
data class CopiedFile(
    /** Path relative to the package root. */
    val path: String,
    /** Where to copy from. */
    val source: Path,
)

/** Everything one target generator produces for one IR. */
data class GeneratedPackage(
    /** Directory of the package relative to the output root, e.g. `flutter/sample_sdk`. */
    val root: String,
    val files: List<GeneratedFile>,
    val copies: List<CopiedFile> = emptyList(),
    val binaries: List<BinaryFile> = emptyList(),
) {
    /** Writes the package under [outputRoot], replacing any previous generated files. */
    fun write(outputRoot: Path): Path {
        val dir = outputRoot.resolve(root)
        files.forEach { f ->
            val target = dir.resolve(f.path)
            Files.createDirectories(target.parent)
            Files.writeString(target, f.content)
            if (f.executable) target.toFile().setExecutable(true, false)
        }
        binaries.forEach { b ->
            val target = dir.resolve(b.path)
            Files.createDirectories(target.parent)
            Files.write(target, b.bytes)
        }
        copies.forEach { c ->
            val target = dir.resolve(c.path)
            Files.createDirectories(target.parent)
            Files.copy(c.source, target, java.nio.file.StandardCopyOption.REPLACE_EXISTING)
        }
        return dir
    }

    /** The files sorted by path, for deterministic listings and golden comparison. */
    fun sortedFiles(): List<GeneratedFile> = files.sortedBy { it.path }
}

/** Inputs a generator needs beyond the IR. */
data class GeneratorContext(
    /** The SDK's `.aar`, copied into the package. `null` in unit tests, which only check text output. */
    val aarFile: Path? = null,
)

/** The first line of every generated file, in the comment syntax of its language (CLAUDE.md hard rule 3). */
object GeneratedHeader {
    fun text(version: String): String = "Generated by Henosis $version. Do not edit."

    fun slash(version: String): String = "// ${text(version)}"

    fun hash(version: String): String = "# ${text(version)}"

    fun xml(version: String): String = "<!-- ${text(version)} -->"
}
