package com.devstrike.henosis.gen.bridge

import com.devstrike.henosis.core.ir.IrJson
import com.devstrike.henosis.testing.Golden
import io.kotest.matchers.collections.shouldContainExactly
import io.kotest.matchers.ints.shouldBeLessThan
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldStartWith
import org.junit.jupiter.api.Test

class BridgeGeneratorTest {
    private val ir = IrJson.decode(Golden.sampleIrJson)
    private val files = BridgeGenerator.generate(ir, "com.devstrike.sample_sdk.bridge")

    @Test
    fun `generates codecs and one bridge per facade`() {
        files.map { it.path } shouldContainExactly listOf("HenosisCodecs.kt", "GreeterBridge.kt", "CounterBridge.kt")
        files.forEach { it.content shouldStartWith "// Generated by Henosis 0.1.0. Do not edit." }
    }

    @Test
    fun `bridge output matches the golden snapshot`() {
        Golden.checkTree("bridge/sample_sdk", files)
    }

    @Test
    fun `facade bridges decode arguments and encode results`() {
        val greeter = files.single { it.path == "GreeterBridge.kt" }.content
        greeter shouldContain "class GreeterBridge(\n    context: Context,\n)"
        greeter shouldContain
            "\"fetchProfile\" -> target.fetchProfile((args[\"id\"] as Number).toLong())?.let { v1 -> HenosisCodecs.encodeProfile(v1) }"
        greeter shouldContain "\"divideDouble\" -> target.divide((args[\"a\"] as Number).toDouble(), (args[\"b\"] as Number).toDouble())"
        greeter shouldContain "\"ticks\" -> target.ticks"
        greeter shouldContain "else -> throw NoSuchMethodException(method)"
        val counter = files.single { it.path == "CounterBridge.kt" }.content
        counter shouldContain "private val target: Counter = Counter()"
        counter shouldContain "\"reset\" -> {"
        counter shouldContain "target.reset()"
    }

    @Test
    fun `codecs rebuild data classes in constructor order`() {
        val codecs = files.single { it.path == "HenosisCodecs.kt" }.content
        codecs shouldContain "public fun decodeProfile(`value`: Map<*, *>): Profile"
        codecs shouldContain "\"level\" to value.level.name"
        codecs shouldContain "Level.valueOf(value[\"level\"] as String)"
        codecs shouldContain "value[\"avatar\"]?.let { v2 -> HenosisCodecs.decodeBytes(v2) }"
        codecs shouldContain "public fun decodeBytes(`value`: Any?): ByteArray"
        codecs.indexOf("value[\"id\"]") shouldBeLessThan codecs.indexOf("value[\"name\"]")
    }
}
