package com.devstrike.henosis.gen.reactnative

import com.devstrike.henosis.core.codegen.GeneratedFile
import com.devstrike.henosis.core.codegen.GeneratedHeader
import com.devstrike.henosis.core.codegen.GeneratedPackage
import com.devstrike.henosis.core.codegen.GeneratorContext
import com.devstrike.henosis.core.ir.Ir

/**
 * The React Native target: a New Architecture TurboModule package (Codegen specs, TypeScript API,
 * Kotlin modules over the shared bridge) with an example app, under `react-native/<package>/`.
 *
 * Reads only the [Ir]. Output is deterministic.
 */
object ReactNativeGenerator {
    const val TARGET = "rn"

    fun generate(
        ir: Ir,
        context: GeneratorContext = GeneratorContext(),
    ): GeneratedPackage {
        val target =
            ir.targets.reactNative
                ?: throw IllegalArgumentException("the IR has no react_native target; add targets.react_native to henosis.yaml")
        val npmName = target.packageName
        val moduleName = target.module
        val androidPackage = TsNames.androidPackage(npmName)
        val ts = TsLibrary(ir, moduleName)
        val android = ReactNativeAndroid(ir, moduleName, androidPackage, context, ts)
        val example = ReactNativeExample(ir, npmName, moduleName, androidPackage)
        val files = mutableListOf<GeneratedFile>()
        files += GeneratedFile("package.json", packageJson(ir, npmName, moduleName, androidPackage))
        files += GeneratedFile("tsconfig.json", tsconfig(ir, npmName))
        files +=
            GeneratedFile(
                "tsconfig.build.json",
                "${GeneratedHeader.slash(
                    ir.henosisVersion,
                )}\n{\n  \"extends\": \"./tsconfig\",\n  \"exclude\": [\"example\", \"lib\"]\n}\n".let {
                    stripHeader(it)
                },
            )
        files += GeneratedFile("babel.config.js", babelConfig(ir))
        files +=
            GeneratedFile(
                ".yarnrc.yml",
                "${GeneratedHeader.hash(ir.henosisVersion)}\nnodeLinker: node-modules\nnmHoistingLimits: workspaces\n",
            )
        files += GeneratedFile(".gitignore", gitignore(ir))
        files += GeneratedFile("README.md", readme(ir, npmName, moduleName))
        files += ts.generate()
        files += android.files()
        files += example.files()
        return GeneratedPackage(
            root = "react-native/${TsNames.directoryName(npmName)}",
            files = files.sortedBy { it.path },
            copies = android.copies(),
            binaries = example.binaries(),
        )
    }

    /** JSON files cannot carry a comment header; they get a `henosis` property instead (see [packageJson]). */
    private fun stripHeader(text: String): String = text.lines().drop(1).joinToString("\n")

    private fun packageJson(
        ir: Ir,
        npmName: String,
        moduleName: String,
        androidPackage: String,
    ): String =
        """
        |{
        |  "name": "$npmName",
        |  "version": "${ir.version}",
        |  "description": "React Native bindings for the ${ir.name} native SDK, generated by Henosis.",
        |  "henosis": "${GeneratedHeader.text(ir.henosisVersion)}",
        |  "main": "./lib/module/index.js",
        |  "types": "./lib/typescript/src/index.d.ts",
        |  "exports": {
        |    ".": {
        |      "${TsNames.sourceCondition(npmName)}": "./src/index.ts",
        |      "types": "./lib/typescript/src/index.d.ts",
        |      "default": "./lib/module/index.js"
        |    },
        |    "./package.json": "./package.json"
        |  },
        |  "files": [
        |    "src",
        |    "lib",
        |    "android",
        |    "react-native.config.js",
        |    "!android/build",
        |    "!android/gradle",
        |    "!android/gradlew",
        |    "!android/gradlew.bat",
        |    "!android/local.properties",
        |    "!**/.*"
        |  ],
        |  "scripts": {
        |    "example": "yarn workspace $npmName-example",
        |    "prepare": "bob build",
        |    "typecheck": "tsc --noEmit"
        |  },
        |  "keywords": [
        |    "react-native",
        |    "android",
        |    "henosis"
