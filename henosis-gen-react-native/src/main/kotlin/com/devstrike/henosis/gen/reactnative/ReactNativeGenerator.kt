        """.trimMargin()

    private fun tsconfig(
        ir: Ir,
        npmName: String,
    ): String =
        """
        |{
        |  "compilerOptions": {
        |    "rootDir": ".",
        |    "paths": {
        |      "$npmName": ["./src/index"]
        |    },
        |    "allowUnreachableCode": false,
        |    "allowUnusedLabels": false,
        |    "customConditions": [
        |      "${TsNames.sourceCondition(npmName)}",
        |      "react-native-strict-api"
        |    ],
        |    "esModuleInterop": true,
        |    "forceConsistentCasingInFileNames": true,
        |    "jsx": "react-jsx",
        |    "lib": ["ESNext"],
        |    "module": "ESNext",
        |    "moduleResolution": "bundler",
        |    "noEmit": true,
        |    "noFallthroughCasesInSwitch": true,
        |    "noImplicitReturns": true,
        |    "noUncheckedIndexedAccess": true,
        |    "noUnusedLocals": true,
        |    "noUnusedParameters": true,
        |    "resolveJsonModule": true,
        |    "skipLibCheck": true,
        |    "strict": true,
        |    "target": "ESNext",
        |    "verbatimModuleSyntax": true
        |  }
        |}
        |
        """.trimMargin().also {
            require(ir.henosisVersion.isNotEmpty())
        }

    private fun babelConfig(ir: Ir): String =
        """
        |${GeneratedHeader.slash(ir.henosisVersion)}
        |module.exports = {
        |  overrides: [
        |    {
        |      exclude: /\/node_modules\//,
        |      presets: ['module:react-native-builder-bob/babel-preset'],
        |    },
        |    {
        |      include: /\/node_modules\//,
        |      presets: ['module:@react-native/babel-preset'],
        |    },
        |  ],
        |};
        |
        """.trimMargin()

    private fun gitignore(ir: Ir): String =
        """
        |${GeneratedHeader.hash(ir.henosisVersion)}
        |.DS_Store
        |.vscode/
        |.idea
        |.gradle
        |.cxx
        |local.properties
        |build/
        |node_modules/
        |npm-debug.log
        |yarn-debug.log
        |yarn-error.log
        |.yarn/*
        |!.yarn/patches
        |!.yarn/plugins
        |!.yarn/releases
        |!.yarn/sdks
        |!.yarn/versions
        |lib/
        |android/generated
        |
        """.trimMargin()

    private fun readme(
        ir: Ir,
        npmName: String,
        moduleName: String,
    ): String {
        val facades =
            ir.facades.joinToString(
                "\n",
            ) { f -> "- `${f.name}` (`${f.nativeClass}`): ${f.methods.size} method(s), ${f.events.size} event(s)" }
        return """
            |${GeneratedHeader.xml(ir.henosisVersion)}
            |# $npmName
            |
            |React Native bindings (New Architecture TurboModules, Android) for the `${ir.name}` native SDK
            |(`${ir.source.coordinates}`), generated by Henosis ${ir.henosisVersion}. Do not edit by hand; change
            |`henosis.yaml` and regenerate.
            |
            |## Facades
            |
            |$facades
            |
            |Each facade is a singleton: `Greeter.instance.greet('name')`. Methods return promises and
            |events expose `addListener(listener, onError?)`, which returns an unsubscribe function.
            |Native failures reject with `HenosisError`, whose `code` is the simple class name of the
            |native exception.
            |
            |Byte arrays are `ArrayBuffer` in TypeScript and cross the bridge as base64 strings, because
            |React Native Codegen cannot type binary data. Kotlin `Long` values arrive as JavaScript
            |numbers and lose precision above 2^53.
            |
            |One TurboModule is registered per facade, named `$moduleName<Facade>`.
            |
            |## Example
            |
            |`example/` exercises every binding: `yarn && yarn example android`.
            |
            """.trimMargin()
    }
}
