package com.devstrike.henosis.gen.reactnative

import com.devstrike.henosis.core.codegen.GeneratorContext
import com.devstrike.henosis.core.ir.IrJson
import com.devstrike.henosis.testing.Golden
import io.kotest.matchers.booleans.shouldBeTrue
import io.kotest.matchers.collections.shouldBeEmpty
import io.kotest.matchers.collections.shouldContain
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import org.junit.jupiter.api.Test

class ReactNativeGeneratorTest {
    private val ir = IrJson.decode(Golden.sampleIrJson)
    private val pkg = ReactNativeGenerator.generate(ir)

    @Test
    fun `every generated file matches the golden snapshot`() {
        pkg.root shouldBe "react-native/sample-sdk"
        Golden.checkTree("react-native/sample-sdk", pkg.files)
    }

    @Test
    fun `every generated file carries the Henosis header`() {
        val offenders =
            pkg.files
                .filterNot {
                    it.content.contains(
                        "Generated by Henosis ${ir.henosisVersion}. Do not edit.",
                    )
                }.map { it.path }
        // JSON files cannot hold comments (package.json carries a "henosis" property instead) and the Gradle
        // wrapper scripts are Gradle's own files, emitted verbatim.
        offenders
            .filterNot {
                it.endsWith(".json") || it == "example/.watchmanconfig" || it.endsWith("gradlew") ||
                    it.endsWith("gradlew.bat")
            }.shouldBeEmpty()
        pkg.files.single { it.path == "package.json" }.content shouldContain "\"henosis\": \"Generated by Henosis"
    }

    @Test
    fun `output is byte-identical across runs`() {
        ReactNativeGenerator.generate(ir).files shouldBe pkg.files
        ReactNativeGenerator.generate(ir).binaries shouldBe pkg.binaries
    }

    @Test
    fun `gradle wrapper is emitted with the script executable and the jar as a binary`() {
        pkg.files
            .single { it.path == "example/android/gradlew" }
            .executable
            .shouldBeTrue()
        pkg.binaries.single().path shouldBe "example/android/gradle/wrapper/gradle-wrapper.jar"
        pkg.binaries
            .single()
            .bytes.size shouldBe
            Golden.repoRoot
                .resolve("gradle/wrapper/gradle-wrapper.jar")
                .toFile()
                .length()
                .toInt()
    }

    @Test
    fun `the aar is copied into a package-local maven repository`() {
        val withAar = ReactNativeGenerator.generate(ir, GeneratorContext(aarFile = Golden.sampleAar))
        withAar.copies.single().path shouldBe "android/libs/maven/henosis/local/sample_sdk/0.1.0/sample_sdk-0.1.0.aar"
        withAar.files.single { it.path == "android/build.gradle" }.content shouldContain "implementation \"henosis.local:sample_sdk:0.1.0\""
        pkg.copies.shouldBeEmpty()
    }

    @Test
    fun `specs declare one TurboModule per facade with codegen-safe types`() {
        val greeter = pkg.files.single { it.path == "src/NativeSampleSdkGreeter.ts" }.content
        greeter shouldContain "fetchProfile(id: number): Promise<Object | null>;"
        greeter shouldContain "echoBytes(data: string): Promise<string>;"
        greeter shouldContain "greetOptional(name: string | null): Promise<string>;"
        greeter shouldContain "addListener(eventName: string): void;"
        greeter shouldContain "TurboModuleRegistry.getEnforcing<Spec>('SampleSdkGreeter')"
        val counter = pkg.files.single { it.path == "src/NativeSampleSdkCounter.ts" }.content
        counter shouldContain "mix(small: number, tiny: number, ratio: number, enabled: boolean): Promise<number>;"
        pkg.files.map { it.path } shouldContain "android/src/main/java/com/devstrike/samplesdk/SampleSdkPackage.kt"
    }

    @Test
    fun `names follow npm and TypeScript conventions`() {
        TsNames.androidPackage("@devstrike/sample-sdk") shouldBe "com.devstrike.samplesdk"
        TsNames.androidPackage("sample-sdk") shouldBe "com.samplesdk"
        TsNames.directoryName("@devstrike/sample-sdk") shouldBe "sample-sdk"
        TsNames.sourceCondition("@devstrike/sample-sdk") shouldBe "devstrike-sample-sdk-source"
        TsNames.fileName("Greeter") shouldBe "greeter"
        TsNames.identifier("default") shouldBe "default_"
    }
}
