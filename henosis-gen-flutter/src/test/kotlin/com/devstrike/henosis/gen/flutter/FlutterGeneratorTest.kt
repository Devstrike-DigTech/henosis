package com.devstrike.henosis.gen.flutter

import com.devstrike.henosis.core.codegen.GeneratorContext
import com.devstrike.henosis.core.ir.IrJson
import com.devstrike.henosis.testing.Golden
import io.kotest.matchers.collections.shouldBeEmpty
import io.kotest.matchers.collections.shouldContain
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldStartWith
import org.junit.jupiter.api.Test

class FlutterGeneratorTest {
    private val ir = IrJson.decode(Golden.sampleIrJson)
    private val pkg = FlutterGenerator.generate(ir)

    @Test
    fun `every generated file matches the golden snapshot`() {
        pkg.root shouldBe "flutter/sample_sdk"
        Golden.checkTree("flutter/sample_sdk", pkg.files)
    }

    @Test
    fun `every generated file starts with the Henosis header`() {
        val offenders =
            pkg.files
                .filterNot {
                    it.content.contains(
                        "Generated by Henosis ${ir.henosisVersion}. Do not edit.",
                    )
                }.map { it.path }
        offenders.shouldBeEmpty()
        pkg.files.forEach { f ->
            val first = f.content.lineSequence().first()
            first shouldContain "Generated by Henosis"
        }
    }

    @Test
    fun `output is byte-identical across runs`() {
        FlutterGenerator.generate(ir).files shouldBe pkg.files
    }

    @Test
    fun `the aar is copied into a package-local maven repository`() {
        val withAar = FlutterGenerator.generate(ir, GeneratorContext(aarFile = Golden.sampleAar))
        withAar.copies.single().path shouldBe "android/libs/maven/henosis/local/sample_sdk/0.1.0/sample_sdk-0.1.0.aar"
        withAar.files.map { it.path } shouldContain "android/libs/maven/henosis/local/sample_sdk/0.1.0/sample_sdk-0.1.0.pom"
        withAar.files.single { it.path == "android/build.gradle.kts" }.content shouldContain
            "implementation(\"henosis.local:sample_sdk:0.1.0\")"
        pkg.copies.shouldBeEmpty()
    }

    @Test
    fun `dart names follow Dart conventions`() {
        DartNames.fileName("Greeter") shouldBe "greeter"
        DartNames.fileName("SampleSdk") shouldBe "sample_sdk"
        DartNames.fileName("HTTPClient") shouldBe "http_client"
        DartNames.enumValue("BRONZE") shouldBe "bronze"
        DartNames.enumValue("GOLD_PLUS") shouldBe "goldPlus"
        DartNames.enumValue("Bronze") shouldBe "bronze"
        DartNames.enumValue("VALUES") shouldBe "values_"
        DartNames.enumValue("DEFAULT") shouldBe "default_"
        DartNames.identifier("in") shouldBe "in_"
        DartNames.identifier("name") shouldBe "name"
        DartNames.pascalCase("sample_sdk") shouldBe "SampleSdk"
    }

    @Test
    fun `the plugin class is registered in pubspec`() {
        pkg.files.single { it.path == "pubspec.yaml" }.content.let {
            it shouldStartWith "# Generated by Henosis"
            it shouldContain "package: com.devstrike.sample_sdk"
            it shouldContain "pluginClass: SampleSdkPlugin"
        }
    }
}
