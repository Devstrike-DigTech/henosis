package com.devstrike.henosis.gen.flutter

import com.devstrike.henosis.core.codegen.CodeWriter
import com.devstrike.henosis.core.codegen.GeneratedFile
import com.devstrike.henosis.core.codegen.GeneratedHeader
import com.devstrike.henosis.core.ir.Ir
import com.devstrike.henosis.core.ir.IrFacade
import com.devstrike.henosis.core.ir.IrType
import com.devstrike.henosis.core.ir.IrTypeKind
import com.devstrike.henosis.core.ir.IrTypeRef

/** Generates the Dart side of the plugin: `lib/<package>.dart` and everything under `lib/src/`. */
internal class DartLibrary(
    private val ir: Ir,
    private val packageName: String,
) {
    private val types = DartTypes(ir)
    private val header = GeneratedHeader.slash(ir.henosisVersion)

    fun generate(): List<GeneratedFile> {
        val files = mutableListOf<GeneratedFile>()
        files += GeneratedFile("lib/$packageName.dart", libraryFile())
        files += GeneratedFile("lib/src/henosis_exception.dart", exceptionFile())
        files += GeneratedFile("lib/src/henosis_channels.dart", channelsFile())
        if (ir.types.isNotEmpty()) files += GeneratedFile("lib/src/types.dart", typesFile())
        ir.facades.forEach { facade -> files += GeneratedFile("lib/src/${DartNames.fileName(facade.name)}.dart", facadeFile(facade)) }
        return files
    }

    private fun libraryFile(): String {
        val w = CodeWriter()
        w.line(header)
        w.line("/// Dart bindings for the `${ir.name}` native SDK, generated by Henosis.")
        w.line("library;")
        w.line()
        w.line("export 'src/henosis_exception.dart';")
        if (ir.types.isNotEmpty()) w.line("export 'src/types.dart';")
        ir.facades.forEach { w.line("export 'src/${DartNames.fileName(it.name)}.dart';") }
        return w.toString()
    }

    private fun exceptionFile(): String =
        """
        |$header
        |
        |/// An error raised by the native SDK while handling a call or an event.
        |///
        |/// [code] is the simple class name of the native exception, for example
        |/// `ArithmeticException` or `IllegalStateException`.
        |class HenosisException implements Exception {
        |  /// Creates an exception with the native [code] and optional [message].
        |  const HenosisException(this.code, this.message);
        |
        |  /// The simple class name of the native exception.
        |  final String code;
        |
        |  /// The native exception's message, if any.
        |  final String? message;
        |
        |  @override
        |  String toString() => message == null
        |      ? 'HenosisException(${'$'}code)'
        |      : 'HenosisException(${'$'}code): ${'$'}message';
        |}
        |
        """.trimMargin()

    private fun channelsFile(): String =
        """
        |$header
        |import 'package:flutter/services.dart';
        |
        |import 'henosis_exception.dart';
        |
        |/// Invokes [method] on [channel], turning platform errors into [HenosisException].
        |Future<Object?> henosisInvoke(
        |  MethodChannel channel,
        |  String method,
        |  Map<String, Object?> arguments,
        |) async {
        |  try {
        |    return await channel.invokeMethod<Object?>(method, arguments);
        |  } on PlatformException catch (e) {
        |    throw HenosisException(e.code, e.message);
        |  }
        |}
        |
        |/// Subscribes to [channel], turning platform errors into [HenosisException].
        |Stream<Object?> henosisEvents(EventChannel channel) {
        |  return channel.receiveBroadcastStream().handleError(
        |    (Object error) {
        |      if (error is PlatformException) {
        |        throw HenosisException(error.code, error.message);
        |      }
        |      throw error;
        |    },
        |  );
        |}
        |
        """.trimMargin()

    private fun typesFile(): String {
        val w = CodeWriter()
        w.line(header)
        w.line("import 'package:flutter/foundation.dart';")
        val dataClasses = ir.types.filter { it.kind == IrTypeKind.DATA_CLASS }
        val needsUnset = dataClasses.any { t -> t.fields.any { it.type.nullable } }
        if (needsUnset) {
            w.line()
            w.line("/// Marks a `copyWith` argument that was not passed, so `null` can be set explicitly.")
            w.line("const Object _unset = Object();")
        }
        ir.types.forEach { type ->
            w.line()
            when (type.kind) {
                IrTypeKind.ENUM -> enumType(w, type)
                else -> dataClassType(w, type)
            }
        }
        return w.toString()
    }

    private fun enumType(
        w: CodeWriter,
        type: IrType,
    ) {
        w.line("/// Mirrors `${type.nativeClass}`.")
        w.block("enum ${type.name} {") {
            type.entries.forEachIndexed { i, entry ->
                val sep = if (i == type.entries.lastIndex) ";" else ","
                line("${DartNames.enumValue(entry)}('$entry')$sep")
            }
            line()
            line("const ${type.name}(this.nativeName);")
            line()
            line("/// The Kotlin enum entry name.")
            line("final String nativeName;")
            line()
            line("/// The entry whose Kotlin name is [name].")
            line("static ${type.name} fromNative(String name) =>")
            indent { line("values.firstWhere((${type.name} value) => value.nativeName == name);") }
        }
    }

    private fun dataClassType(
        w: CodeWriter,
        type: IrType,
    ) {
        val fields = type.fields.map { it.copy(name = DartNames.identifier(it.name)) to it.name }
        w.line("/// Mirrors `${type.nativeClass}`.")
        w.line("@immutable")
        w.block("class ${type.name} {") {
            // constructor
            line("/// Creates a ${type.name}.")
            line("const ${type.name}({")
            indent {
                fields.forEach { (f, _) -> line(if (f.type.nullable) "this.${f.name}," else "required this.${f.name},") }
            }
            line("});")
            line()
            // fromMap
            line("/// Rebuilds a ${type.name} from the map the native side sends.")
            block("factory ${type.name}.fromMap(Map<Object?, Object?> map) {") {
                fields.forEach { (f, wire) -> line("final Object? ${f.name} = map['$wire'];") }
                line("return ${type.name}(")
                indent { fields.forEach { (f, _) -> line("${f.name}: ${types.decode(f.type, f.name)},") } }
                line(");")
            }
            fields.forEach { (f, _) ->
                line()
                line("/// The `${f.name}` field.")
                line("final ${types.name(f.type)} ${f.name};")
            }
            line()
            // copyWith
            line("/// Returns a copy with the given fields replaced.")
            line("${type.name} copyWith({")
            indent {
                fields.forEach { (f, _) ->
                    line(if (f.type.nullable) "Object? ${f.name} = _unset," else "${types.name(f.type)}? ${f.name},")
                }
            }
            line("}) {")
            indent {
                line("return ${type.name}(")
                indent {
                    fields.forEach { (f, _) ->
                        if (f.type.nullable) {
                            line("${f.name}: ${f.name} == _unset ? this.${f.name} : ${f.name} as ${types.name(f.type)},")
                        } else {
                            line("${f.name}: ${f.name} ?? this.${f.name},")
                        }
                    }
                }
                line(");")
            }
            line("}")
            line()
            // toMap
            line("/// Encodes this ${type.name} for the native side.")
            block("Map<String, Object?> toMap() {") {
                line("return <String, Object?>{")
                indent { fields.forEach { (f, wire) -> line("'$wire': ${types.encode(f.type, f.name)},") } }
                line("};")
            }
            line()
            // ==
            line("@override")
            block("bool operator ==(Object other) {") {
                line("if (identical(this, other)) {")
                indent { line("return true;") }
                line("}")
                line("return other is ${type.name} &&")
                indent {
                    fields.forEachIndexed { i, (f, _) ->
                        val end = if (i == fields.lastIndex) ";" else " &&"
                        line(equality(f.type, f.name) + end)
                    }
                }
            }
            line()
            // hashCode
            line("@override")
            line("int get hashCode => Object.hashAll(<Object?>[")
            indent { fields.forEach { (f, _) -> line("${hash(f.type, f.name)},") } }
            line("]);")
            line()
            // toString
            line("@override")
            line("String toString() =>")
            indent { line("'${type.name}(" + fields.joinToString(", ") { (f, _) -> "${f.name}: \$${f.name}" } + ")';") }
        }
    }

    private fun equality(
        type: IrTypeRef,
        name: String,
    ): String =
        when (type.kind) {
            IrTypeKind.LIST, IrTypeKind.BYTE_ARRAY -> "listEquals($name, other.$name)"
            IrTypeKind.MAP -> "mapEquals($name, other.$name)"
            else -> "$name == other.$name"
        }

    private fun hash(
        type: IrTypeRef,
        name: String,
    ): String =
        when (type.kind) {
            IrTypeKind.LIST, IrTypeKind.BYTE_ARRAY -> {
                if (type.nullable) "$name == null ? null : Object.hashAll($name!)" else "Object.hashAll($name)"
            }

            IrTypeKind.MAP -> {
                if (type.nullable) {
                    "$name == null ? null : Object.hashAllUnordered($name!.entries.map((e) => Object.hash(e.key, e.value)))"
                } else {
                    "Object.hashAllUnordered($name.entries.map((e) => Object.hash(e.key, e.value)))"
                }
            }

            else -> {
                name
            }
        }

    private fun facadeFile(facade: IrFacade): String {
        val w = CodeWriter()
        w.line(header)
        val allTypes = facade.methods.flatMap { m -> m.parameters.map { it.type } + m.returnType } + facade.events.map { it.elementType }
        w.line("import 'package:flutter/services.dart';")
        w.line()
        w.line("import 'henosis_channels.dart';")
        if (allTypes.any { types.usesTypes(it) }) w.line("import 'types.dart';")
        w.line()
        w.line("/// Bindings for `${facade.nativeClass}`.")
        w.line("///")
        w.line("/// The native object is a singleton owned by the plugin; use [instance].")
        w.block("class ${facade.name} {") {
            line("${facade.name}._();")
            line()
            line("/// The shared instance.")
            line("static final ${facade.name} instance = ${facade.name}._();")
            line()
            line("static const MethodChannel _channel = MethodChannel('${channelName(facade)}');")
            facade.events.forEach { event ->
                line("static const EventChannel _${event.name}Channel =")
                indent { line("EventChannel('${channelName(facade)}/${event.name}');") }
            }
            facade.methods.forEach { method ->
                line()
                line("/// Calls `${facade.nativeClass}.${method.nativeName}`.")
                val params = method.parameters.joinToString(", ") { "${types.name(it.type)} ${DartNames.identifier(it.name)}" }
                val returns = if (method.returnType.kind == IrTypeKind.UNIT) "Future<void>" else "Future<${types.name(method.returnType)}>"
                block("$returns ${method.name}($params) async {") {
                    val args =
                        if (method.parameters.isEmpty()) {
                            "const <String, Object?>{}"
                        } else {
                            "<String, Object?>{" +
                                method.parameters.joinToString(
                                    ", ",
                                ) { "'${it.name}': ${types.encode(it.type, DartNames.identifier(it.name))}" } +
                                "}"
                        }
                    if (method.returnType.kind == IrTypeKind.UNIT) {
                        line("await henosisInvoke(_channel, '${method.name}', $args);")
                    } else {
                        line("final Object? result = await henosisInvoke(_channel, '${method.name}', $args);")
                        line("return ${types.decode(method.returnType, "result")};")
                    }
                }
            }
            facade.events.forEach { event ->
                line()
                line("/// Events from `${facade.nativeClass}.${event.nativeName}`.")
                line("Stream<${types.name(event.elementType)}> get ${event.name} =>")
                indent { line("henosisEvents(_${event.name}Channel).map((Object? event) => ${types.decode(event.elementType, "event")});") }
            }
        }
        return w.toString()
    }

    private fun channelName(facade: IrFacade) = "henosis/${ir.name}/${facade.name}"
}
