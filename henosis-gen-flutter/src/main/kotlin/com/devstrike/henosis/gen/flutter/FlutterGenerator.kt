package com.devstrike.henosis.gen.flutter

import com.devstrike.henosis.core.codegen.CodeWriter
import com.devstrike.henosis.core.codegen.GeneratedFile
import com.devstrike.henosis.core.codegen.GeneratedHeader
import com.devstrike.henosis.core.codegen.GeneratedPackage
import com.devstrike.henosis.core.codegen.GeneratorContext
import com.devstrike.henosis.core.ir.Ir

/**
 * The Flutter target: a complete plugin package (Dart API, Android plugin glue over the shared
 * Kotlin bridge, and an example app) under `flutter/<package>/`.
 *
 * Reads only the [Ir]. Output is deterministic: no timestamps, sorted members, fixed templates.
 */
object FlutterGenerator {
    const val TARGET = "flutter"

    fun generate(
        ir: Ir,
        context: GeneratorContext = GeneratorContext(),
    ): GeneratedPackage {
        val target =
            ir.targets.flutter ?: throw IllegalArgumentException("the IR has no flutter target; add targets.flutter to henosis.yaml")
        val packageName = target.packageName
        val androidPackage = "${target.org}.$packageName"
        val android = FlutterAndroid(ir, packageName, androidPackage, context)
        val files = mutableListOf<GeneratedFile>()
        files += GeneratedFile("pubspec.yaml", pubspec(ir, packageName, androidPackage, android.pluginClassName))
        files +=
            GeneratedFile(
                "analysis_options.yaml",
                "${GeneratedHeader.hash(
                    ir.henosisVersion,
                )}\nanalyzer:\n  exclude:\n    - build/**\n    - android/**\ninclude: package:flutter_lints/flutter.yaml\n",
            )
        files += GeneratedFile("README.md", readme(ir, packageName))
        files += GeneratedFile(".gitignore", gitignore(ir))
        files += DartLibrary(ir, packageName).generate()
        files += GeneratedFile("test/${packageName}_test.dart", DartTests(ir, packageName).generate())
        files += android.files()
        files += FlutterExample(ir, packageName, androidPackage).files()
        return GeneratedPackage(root = "$TARGET/$packageName", files = files.sortedBy { it.path }, copies = android.copies())
    }

    /** `analysis_options.yaml` as `flutter pub get` expects it, so the tool never rewrites the generated file. */
    internal fun analysisOptions(version: String): String =
        CodeWriter()
            .line(GeneratedHeader.hash(version))
            .line("analyzer:")
            .line("  exclude:")
            .line("    - build/**")
            .line("    - android/**")
            .line("include: package:flutter_lints/flutter.yaml")
            .toString()

    private fun pubspec(
        ir: Ir,
        packageName: String,
        androidPackage: String,
        pluginClass: String,
    ): String =
        """
        |${GeneratedHeader.hash(ir.henosisVersion)}
        |name: $packageName
        |description: "Flutter bindings for the ${ir.name} native SDK, generated by Henosis."
        |version: ${ir.version}
        |
        |environment:
        |  sdk: ${FlutterToolchain.DART_SDK_CONSTRAINT}
        |  flutter: '${FlutterToolchain.FLUTTER_CONSTRAINT}'
        |
        |dependencies:
        |  flutter:
        |    sdk: flutter
        |
        |dev_dependencies:
        |  flutter_test:
        |    sdk: flutter
        |  flutter_lints: ${FlutterToolchain.FLUTTER_LINTS}
        |
        |flutter:
        |  plugin:
        |    platforms:
        |      android:
        |        package: $androidPackage
        |        pluginClass: $pluginClass
        |
        """.trimMargin()

    private fun readme(
        ir: Ir,
        packageName: String,
    ): String {
        val facades =
            ir.facades.joinToString(
                "\n",
            ) { f -> "- `${f.name}` (`${f.nativeClass}`): ${f.methods.size} method(s), ${f.events.size} event(s)" }
        return """
            |${GeneratedHeader.xml(ir.henosisVersion)}
            |# $packageName
            |
            |Flutter bindings for the `${ir.name}` native Android SDK (`${ir.source.coordinates}`),
            |generated by Henosis ${ir.henosisVersion}. Do not edit by hand; change `henosis.yaml` and regenerate.
            |
            |## Facades
            |
            |$facades
            |
            |Each facade is a singleton: `Greeter.instance.greet('name')`. Methods return `Future`s and
            |events are `Stream`s. Native failures surface as `HenosisException(code, message)`, where
            |`code` is the simple class name of the native exception.
            |
            |Calls run on the Android main thread inside the plugin's coroutine scope; `suspend`
            |functions suspend there, so long-running synchronous SDK calls should be avoided or
            |made `suspend` in the SDK.
            |
            |## Example
            |
            |`example/` exercises every binding: `cd example && flutter run`.
            |
            """.trimMargin()
    }

    private fun gitignore(ir: Ir): String =
        """
        |${GeneratedHeader.hash(ir.henosisVersion)}
        |*.class
        |*.log
        |*.pyc
        |*.swp
        |.DS_Store
        |.atom/
        |.build/
        |.buildlog/
        |.history
        |.svn/
        |.swiftpm/
        |migrate_working_dir/
        |*.iml
        |*.ipr
        |*.iws
        |.idea/
        |/pubspec.lock
        |**/doc/api/
        |.dart_tool/
        |.flutter-plugins-dependencies
        |/build/
        |/coverage/
        |
        """.trimMargin()
}
